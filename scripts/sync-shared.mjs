// Copies /shared/src into supabase/functions/_shared/scenic so Edge Functions can import it.
//
// Why: Supabase bundles each function from inside supabase/functions/, so code outside that folder
// isn't guaranteed to deploy. /shared stays the single source of truth; the copy is generated.
// Run: npm run sync-shared   (also runs automatically before tests and deploys)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'shared', 'src');
const dest = path.join(root, 'supabase', 'functions', '_shared', 'scenic');

const HEADER =
  '// GENERATED by scripts/sync-shared.mjs from shared/src — DO NOT EDIT. Edit /shared instead.\n';

fs.rmSync(dest, { recursive: true, force: true });
fs.mkdirSync(dest, { recursive: true });

const files = fs.readdirSync(src).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'));

for (const file of files) {
  const code = fs.readFileSync(path.join(src, file), 'utf8');
  fs.writeFileSync(path.join(dest, file), HEADER + code);
}

console.log(`sync-shared: copied ${files.length} files to ${path.relative(root, dest)}`);
